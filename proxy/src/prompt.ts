import { TEXT_JUDGMENT_EXAMPLES } from './promptExamples';

/**
 * PRD §8.2(후기 내용/사진 기준)를 그대로 지시문으로 포함해,
 * 모델이 정책 문서 기준으로만 판단하게 한다 (스펙 §5.1).
 */
export function buildPrompt(
  reviewType: string,
  contentText: string,
  photos: Array<{ declared_category: string; before_after_slot?: 'BEFORE' | 'AFTER' }>,
  procedure?: { is_before_after_exempt: boolean },
  hospitalName?: string,
  profanityCandidate?: boolean
): string {
  const examplesSection = TEXT_JUDGMENT_EXAMPLES.map(
    (e) => `- "${e.text}" → ${e.label === 'APPROVE' ? '승인' : '보류'} (${e.reason})`
  ).join('\n');

  const photoListSection = photos.length
    ? photos
        .map((p, i) => {
          if (p.declared_category !== 'BEFORE_AFTER') return `${i + 1}번: 일반 사진`;
          const slotLabel = p.before_after_slot === 'BEFORE' ? ' (전)' : p.before_after_slot === 'AFTER' ? ' (후)' : '';
          return `${i + 1}번: 시술 전/후 사진${slotLabel}`;
        })
        .join('\n')
    : '(등록된 사진 없음)';

  const beforeAfterPhotos = photos.filter((p) => p.declared_category === 'BEFORE_AFTER');
  const hasBeforeSlot = beforeAfterPhotos.some((p) => p.before_after_slot === 'BEFORE');
  const hasAfterSlot = beforeAfterPhotos.some((p) => p.before_after_slot === 'AFTER');
  const isExemptProcedure = procedure?.is_before_after_exempt === true;
  const onlyOneSlotRegistered = !isExemptProcedure && hasBeforeSlot !== hasAfterSlot;

  const exemptSection = isExemptProcedure
    ? '\n이 후기의 시술은 시술 전/후 촬영이 불가능한 예외 시술로 등록되어 있습니다. \'시술 전/후 사진\'으로 등록된 사진이 실제 전후 비교 사진인지는 확인하지 말고, 처음부터 [승인 기준 - 사진]의 일반 사진 기준으로만 판정하세요.'
    : '';

  const onlyOneSlotSection = onlyOneSlotRegistered
    ? '\n이 후기는 \'시술 전/후 사진\'으로 등록됐지만 전/후 중 한쪽 사진만 첨부되어 있습니다. 이 경우 전후 비교가 성립하는지 판단하지 말고, 무조건 일반 사진으로 유형 변경 후 [승인 기준 - 사진] 기준으로만 판정하고 reasoning에 "일반 사진으로 유형 변경 후 승인 가능" 여부를 명시하세요.'
    : '';

  const profanityCandidateSection = profanityCandidate
    ? '\n자동 필터가 이 후기 내용에 욕설/비속어로 의심되는 패턴이 있다고 표시했습니다. 이 필터는 정상적인 단어 조합을 오탐하는 경우가 있으므로(예: "새로운 지점이"처럼 무관한 문장을 욕설로 오판), 아래 원문을 처음부터 끝까지 직접 읽고 실제로 욕설·비속어·선정적 표현이 있는지 신중히 재확인하세요. 실제로는 문제없는 정상적인 문장이면 이 표시를 무시하고, 진짜 욕설/비속어가 있을 때만 content_flag를 "profanity"로 설정하세요.'
    : '';

  const hospitalNameContextLine = hospitalName ? `\n후기 등록 병원명: ${hospitalName}` : '';
  const hospitalNameCheckSection = hospitalName
    ? `사진마다 "hospital_name_match" 필드를 반드시 채우세요: 사진에 병원명(간판/로고 등 글자)이 보이면 그 이름이 후기 등록 병원명인 "${hospitalName}"과 일치하는 병원인지 대조해 true/false로 답하세요(건물 외벽에 여러 업체 간판이 함께 있어도 "${hospitalName}"과 일치하는 간판이 하나라도 있으면 true). 이름을 대조할 때 "의원/클리닉/성형외과/피부과/한의원/병원" 등 병원 유형을 나타내는 접미사 차이는 무시하고 핵심 브랜드명이 같으면 일치로 판단하세요(예: "루비의원"과 "루비클리닉"은 일치). 핵심 브랜드명 자체가 다르면 접미사가 같아도 불일치입니다(예: "루비의원"과 "여신의원"은 불일치). 병원명 글자가 전혀 안 보이는 사진(의료기기·약품·파우더룸 등 다른 요소로 병원임을 알아본 경우)이거나 병원 내외부 사진이 아니면 null로 두세요. false로 답한 사진은 실제 relevant/flag 판단과 무관하게 이 후기와 무관한 건물/타병원 사진으로 자동 보류 처리됩니다.\n`
    : '';

  return `당신은 후기 검수 담당자를 돕는 판정 보조자입니다. 아래 정책 기준으로만 판단하세요.

후기 내용이 한국어가 아니면 먼저 마음속으로 한국어로 번역한 뒤, 번역된 의미를 기준으로 아래 기준을 그대로 적용해 판단하세요. reasoning은 항상 한국어로 작성하세요.

[승인 기준 - 후기 내용] 시술과 관련된 내용이면 승인. 의미를 알 수 없는 내용(예: ㄱㄴㄷㄹㅁ, 가나다라마바사, ★★★★★★★★★)이거나 이름·전화번호·이메일 등 개인정보가 포함되면 content_flag를 "meaningless"로 보류. 욕설·비속어·선정적 표현이 포함되면 content_flag를 "profanity"로 보류. 사회 공공질서/미풍양속에 위배되면 content_flag를 "public_order"로 보류.${profanityCandidateSection}

[후기 내용 판정 참고 예시]
${examplesSection}

[승인 기준 - 사진] 시술 부위/신체 일부, 시술 관련 장비·약품, 병원 내외부, 앱 결제 화면, 관련 캡쳐 화면은 승인. 식별 불가하거나 미풍양속에 위배되거나 시술과 무관하거나 이름·휴대전화번호·이메일 주소 등 개인정보·민감정보가 노출되면 보류.
사진 속 신체 부위가 후기에 언급된 시술 부위와 다르더라도(예: 다른 신체 부위) 신체 부위/장비·약품/병원 내외부/결제 화면/관련 캡쳐 중 하나에 해당하면 "시술과 무관"을 이유로 보류하지 말고 승인하세요. 여기서 "시술과 무관"은 위 카테고리 어디에도 속하지 않는 사진(예: 음식, 풍경, 시술과 전혀 관계없는 사물)에만 적용합니다.
사진이 SNS 게시물 캡처(좋아요·댓글 수, 다른 게시물 넘김 표시 등이 보이는 화면), 웨딩스냅·여행·카페 음료 등 일상 사진처럼 보여도 마찬가지입니다 — 그 사진 안에 신체 일부(손, 팔, 얼굴, 몸 등)가 하나라도 식별 가능하게 나온다면 "SNS 캡처/일상 사진이라 시술과 무관"이라는 이유로 보류하지 말고 신체 일부 사진으로 승인하세요. 신체가 전혀 나오지 않는 순수 풍경·사물·음식 사진일 때만 시술과 무관으로 보류합니다.
단, 사진 속 인물이 연예인·인플루언서 등 널리 알려진 제3자 유명인으로 식별되면(실제 후기 작성자 본인일 수 없는 경우), 신체 일부가 나오더라도 승인하지 말고 relevant: false, flag: 'irrelevant'로 판정하고 reasoning에 그 이유(유명인 사진으로 추정)를 명시하세요. 사진의 촬영 품질이 높거나 스튜디오 촬영처럼 보인다는 이유만으로는 보류하지 마세요 — 고품질 사진도 실제 고객 본인의 사진일 수 있습니다.
이 서비스는 피부/성형 시술 후기 플랫폼이므로 시술 부위를 보여주기 위한 목적의 노출(가슴·엉덩이·복부 등 시술 부위가 그대로 노출된 사진 포함)은 그 자체만으로 미풍양속 위배가 아니며 신체 일부 사진으로 승인하세요. 다만 노출이 시술 부위 확인 목적을 벗어나 선정적으로 연출된 경우(예: 성적으로 자극적인 포즈·표정, 속옷/란제리 착용 컷, 일반적인 시술 전후 사진 관례를 벗어난 과도한 노출 수위)에는 flag를 'public_order'로 설정해 보류하세요.
${hospitalNameCheckSection}"병원 내외부"로 승인하려면 사진에 시술 배너, 병원명(간판/로고), 의료기기, 약품, 파우더룸, 시술 관련 팜플렛/안내문, 의료진(의사·간호사 등) 중 하나 이상이 나와서 병원임을 알아볼 수 있어야 합니다. 이런 요소 없이 복도·천장·바닥·일반 가구·커튼 등 병원인지 특정할 수 없는 공간만 나온 사진은 시술과 무관한 것으로 보고 보류하세요. 리셉션 데스크나 대기실 소파처럼 그 자체만으로는 병원 여부를 특정할 수 없는 공간도 위 요소가 함께 나오지 않으면 보류하세요. 정수기·커피머신·냉장고·음료/다과 비품 등 대기실 편의시설만 나온 사진, 병원명 글자가 또렷이 식별되지 않는 건물 출입구·로비 외경 사진도 위 요소에 해당하지 않으므로 병원 내외부로 인정하지 말고 보류하세요.
각 사진마다 "body_part_visible" 필드를 반드시 채우세요: 사진 안에 신체 일부(손, 팔, 다리, 발, 얼굴, 몸통, 피부 등)가 하나라도 식별 가능하게 나오면 true, 신체가 전혀 나오지 않으면 false로 답하세요. 이 필드는 그 사진이 시술과 관련 있어 보이는지, 배경이 일상적인지와는 무관하게 신체 일부가 실제로 보이는지만 독립적으로 판단합니다.

"식별 가능"은 사진에 찍힌 대상(신체 부위/장비/화면/장소 등)이 무엇인지 알아볼 수 있다는 뜻입니다 — 사람 얼굴이나 신원을 알아볼 수 있는지와는 무관합니다. 얼굴이 안 보이거나 가려져 있어도, 또는 사람이 전혀 나오지 않는 사진(장비, 병원 간판, 결제 화면 등)이어도 사진 내용 자체를 알아볼 수 있으면 identifiable: true 입니다. 사진이 너무 흐리거나 어둡거나 잘려서 무엇을 찍었는지조차 알 수 없을 때만 identifiable: false로 판단하세요.
신체 일부 사진을 판단할 때 살구색/피부색 톤이라는 이유만으로 곧바로 "피부"라고 단정하지 마세요. 모공, 잔주름, 체모, 혈관, 피부결처럼 실제로 피부라고 알아볼 수 있는 질감·형태가 보여야 identifiable: true입니다. 그런 질감 없이 초점이 안 맞아 뭉개진 단색·저해상도 면만 보이는 사진(벽, 이불, 옷감과도 구분이 안 되는 수준)은 피부인지 다른 사물인지 알 수 없는 것이므로 identifiable: false로 판단하세요.

[사진 유형 - 일반 사진 vs 시술 전/후 사진] 고객은 사진을 첨부할 때 '일반 사진' 또는 '시술 전/후 사진' 중 하나로 유형을 선택하고, 시술 전/후 사진은 각 장마다 '전' 또는 '후'로 등록합니다. 아래 [사진 목록]에 각 사진의 등록 유형과 전/후 구분이 표시되어 있습니다.
- '시술 전/후 사진'으로 등록됐다면 '전' 사진과 '후' 사진이 같은 신체 부위를 촬영해 실제로 전후 비교를 보여주는지 확인하세요(후기에 언급된 시술 부위와 일치하는지는 확인하지 마세요 — '전'과 '후'가 서로 같은 부위인지만 확인하면 됩니다). 서로 다른 부위이거나 비교 관계가 없는 사진이면 비교 사진으로 인정하지 마세요. 맞으면 위 [승인 기준 - 사진]대로 판단합니다.
- '전' 사진과 '후' 사진이 서로 완전히 동일한 이미지(구도·배경·인물·촬영 시점까지 구별되지 않는 같은 사진)라면 실제 전후 비교가 성립하지 않습니다. 이 경우 '후' 사진을 relevant: false, flag: 'irrelevant'로 판정하고 reasoning에 "전/후 사진이 동일함"이라고 명시하세요.
- '시술 전/후 사진'으로 등록됐지만 실제로는 전후 비교 사진이 아닌 경우(예: 장비, 병원 내외부, 결제 화면 등), 위 [승인 기준 - 사진]의 다른 승인 대상(장비/병원/결제 화면/캡쳐 등)에 해당하는지 다시 확인하세요. 해당하면 relevant/identifiable을 그 기준대로 true로, flag는 null로 판정하고 reasoning에 "일반 사진으로 유형 변경 후 승인 가능"이라고 명시하세요. 그 기준에도 못 미치면(시술과 무관, 식별 불가, 미풍양속 위배) 유형 변경 없이 그대로 보류 판정하세요.
- '일반 사진'으로 등록된 사진은 시술 전후 비교 사진이 아니어도 됩니다 — [승인 기준 - 사진]대로만 판단하고, 시술 전/후 사진 기준으로 격상 판단하지 마세요.${exemptSection}${onlyOneSlotSection}

후기 유형: ${reviewType}${hospitalNameContextLine}
후기 내용: ${contentText}
[사진 목록]
${photoListSection}
(아래 이미지 순서와 위 목록/photos 배열 순서가 동일합니다)

각 사진과 후기 내용을 위 기준으로 개별 판단해 지정된 JSON 스키마 형식으로 결과를 제출하세요.`;
}
